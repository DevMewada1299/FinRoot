"""Ports. Only the gateway (and the seed script) may hold a writable RecordPort or BankPort."""
from __future__ import annotations

from typing import Protocol

from probation.models import (
    BankAccountRecord, Cents, PaymentEntry, PurchaseInvoice, PurchaseOrder,
    PurchaseReceipt, RawRow, Supplier,
)


class RecordPort(Protocol):
    def get_supplier(self, supplier_id: str) -> Supplier: ...
    def bank_history(self, supplier_id: str) -> list[BankAccountRecord]: ...
    def get_po(self, po_id: str) -> PurchaseOrder: ...
    def get_receipts(self, po_id: str) -> list[PurchaseReceipt]: ...
    def changes_since(self, cursor: str) -> tuple[list[RawRow], str]: ...
    # gateway only
    def post_purchase_invoice(self, inv: PurchaseInvoice) -> str: ...
    def post_payment_entry(self, pay: PaymentEntry) -> str: ...
    def add_bank_account(self, acct: BankAccountRecord) -> str: ...
    def set_supplier_status(self, supplier_id: str, status: str) -> None: ...


class BankPort(Protocol):
    def send_ach(self, entity_id: str, account: str, amount: Cents, memo: str) -> str: ...
    def status(self, transfer_id: str) -> str: ...
